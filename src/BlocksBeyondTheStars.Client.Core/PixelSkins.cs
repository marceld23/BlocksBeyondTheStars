using System;
using System.Collections.Generic;
using System.Text.Json;
using BlocksBeyondTheStars.Shared.State;

namespace BlocksBeyondTheStars.Client
{
    /// <summary>
    /// #2682: one pixel skin — what a player paints in the Appearance editor (the face and the body paintings of torso, arms,
    /// legs and helmet, in the shared format of <see cref="BodyPaint"/>: one base32 palette symbol per pixel, 0 = transparent)
    /// plus the five base colours as palette indices (the bare skin, the hair, and the tint under each part's transparent
    /// pixels and on its unpainted faces). A pioneer NPC wears one, recoloured by its seed (<see cref="PixelSkins"/>).
    /// </summary>
    public sealed class PixelSkin
    {
        public string Key { get; set; } = string.Empty;
        public string Author { get; set; } = string.Empty;

        /// <summary>The bare skin (palette index 1..31): the face's transparent pixels and the head, neck and hands.</summary>
        public int Skin { get; set; }

        /// <summary>The hair (palette index; 0 = bald).</summary>
        public int Hair { get; set; }

        public int Torso { get; set; }
        public int Arms { get; set; }
        public int Legs { get; set; }

        /// <summary>The 32 × 32 face ("" = the plain procedural face).</summary>
        public string FacePixels { get; set; } = string.Empty;

        public string TorsoPixels { get; set; } = string.Empty;
        public string ArmPixels { get; set; } = string.Empty;
        public string LegPixels { get; set; } = string.Empty;
        public string HelmetPixels { get; set; } = string.Empty;

        /// <summary>The painting of a <see cref="BodyPaint"/> part index ("" for an unknown part).</summary>
        public string PartPixels(int part) => part switch
        {
            BodyPaint.Torso => TorsoPixels,
            BodyPaint.Arms => ArmPixels,
            BodyPaint.Legs => LegPixels,
            BodyPaint.Helmet => HelmetPixels,
            _ => string.Empty,
        };
    }

    /// <summary>
    /// #2682: the pool of pixel skins the pioneers wear — <c>data/pioneer_skins.json</c> (generated by
    /// <c>tools/gen_pioneer_skins.py</c>; a skin painted in the game's Appearance editor is added with its
    /// <c>--from-settings</c>, see docs/developer/WILDERNESS_FOLK.md). <see cref="Parse"/> keeps the valid entries only;
    /// <see cref="Validate"/> names every problem (the content test). The built skins are cached per seed.
    /// </summary>
    public sealed class PixelSkinPool
    {
        /// <summary>The face's pixel count (32 × 32).</summary>
        public const int FacePixelCount = 32 * 32;

        /// <summary>Built skins kept per seed at most (a world has one or two pioneers; the cache only spares the rebuild).</summary>
        public const int CacheCap = 64;

        private readonly Dictionary<int, PixelSkin> _built = new Dictionary<int, PixelSkin>();

        public PixelSkinPool(IReadOnlyList<PixelSkin> skins)
        {
            Skins = skins ?? Array.Empty<PixelSkin>();
        }

        public IReadOnlyList<PixelSkin> Skins { get; }

        /// <summary>The pool's valid skins from the file's text (an unreadable file is an empty pool — the pioneers then wear
        /// the plain NPC look).</summary>
        public static PixelSkinPool Parse(string json)
        {
            var skins = new List<PixelSkin>();
            foreach (var (skin, problems) in ReadEntries(json, out _))
            {
                if (problems.Count == 0)
                {
                    skins.Add(skin);
                }
            }

            return new PixelSkinPool(skins);
        }

        /// <summary>Every problem of the file (empty = valid): unreadable JSON, no skins, a key missing or twice, a base
        /// colour out of the palette, a painting of the wrong length or with a symbol outside the palette.</summary>
        public static IReadOnlyList<string> Validate(string json)
        {
            var all = new List<string>();
            var entries = ReadEntries(json, out string? fileProblem);
            if (fileProblem is not null)
            {
                all.Add(fileProblem);
                return all;
            }

            if (entries.Count == 0)
            {
                all.Add("the pool has no skins");
            }

            var keys = new HashSet<string>(StringComparer.Ordinal);
            foreach (var (skin, problems) in entries)
            {
                all.AddRange(problems);
                if (skin.Key.Length > 0 && !keys.Add(skin.Key))
                {
                    all.Add($"skin '{skin.Key}' appears twice");
                }
            }

            return all;
        }

        /// <summary>The skin a pioneer with this seed wears: one of the pool picked by the seed, its garments, skin tone and
        /// hair recoloured by it (<see cref="PixelSkins.Recolour"/>). Null for an empty pool. Cached per seed.</summary>
        public PixelSkin? SkinFor(int seed)
        {
            if (Skins.Count == 0)
            {
                return null;
            }

            if (_built.TryGetValue(seed, out var cached))
            {
                return cached;
            }

            if (_built.Count >= CacheCap)
            {
                _built.Clear();
            }

            var source = Skins[(int)(PixelSkins.Mix((uint)seed, 1u) % (uint)Skins.Count)];
            var built = PixelSkins.Recolour(source, seed);
            _built[seed] = built;
            return built;
        }

        private static List<(PixelSkin Skin, List<string> Problems)> ReadEntries(string json, out string? fileProblem)
        {
            fileProblem = null;
            var list = new List<(PixelSkin, List<string>)>();
            JsonDocument doc;
            try
            {
                doc = JsonDocument.Parse(json ?? string.Empty, new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true });
            }
            catch (JsonException e)
            {
                fileProblem = "the pool is not readable JSON: " + e.Message;
                return list;
            }

            using (doc)
            {
                if (doc.RootElement.ValueKind != JsonValueKind.Object
                    || !doc.RootElement.TryGetProperty("skins", out var skins) || skins.ValueKind != JsonValueKind.Array)
                {
                    fileProblem = "the pool has no 'skins' array";
                    return list;
                }

                int index = 0;
                foreach (var e in skins.EnumerateArray())
                {
                    list.Add(ReadEntry(e, index++));
                }
            }

            return list;
        }

        private static (PixelSkin, List<string>) ReadEntry(JsonElement e, int index)
        {
            var problems = new List<string>();
            var skin = new PixelSkin();
            if (e.ValueKind != JsonValueKind.Object)
            {
                problems.Add($"skin #{index} is not an object");
                return (skin, problems);
            }

            skin.Key = Text(e, "key");
            skin.Author = Text(e, "author");
            string name = skin.Key.Length > 0 ? $"skin '{skin.Key}'" : $"skin #{index}";
            if (skin.Key.Length == 0)
            {
                problems.Add($"{name} has no key");
            }

            skin.Skin = Index(e, "skin", name, problems, allowNone: false);
            skin.Hair = Index(e, "hair", name, problems, allowNone: true);
            skin.Torso = Index(e, "torso", name, problems, allowNone: false);
            skin.Arms = Index(e, "arms", name, problems, allowNone: false);
            skin.Legs = Index(e, "legs", name, problems, allowNone: false);
            skin.FacePixels = Painting(e, "facePixels", FacePixelCount, name, problems);
            skin.TorsoPixels = Painting(e, "torsoPixels", BodyPaint.ExpectedLength(BodyPaint.Torso), name, problems);
            skin.ArmPixels = Painting(e, "armPixels", BodyPaint.ExpectedLength(BodyPaint.Arms), name, problems);
            skin.LegPixels = Painting(e, "legPixels", BodyPaint.ExpectedLength(BodyPaint.Legs), name, problems);
            skin.HelmetPixels = Painting(e, "helmetPixels", BodyPaint.ExpectedLength(BodyPaint.Helmet), name, problems);
            return (skin, problems);
        }

        private static string Text(JsonElement e, string property)
            => e.TryGetProperty(property, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() ?? string.Empty : string.Empty;

        private static int Index(JsonElement e, string property, string name, List<string> problems, bool allowNone)
        {
            if (!e.TryGetProperty(property, out var v) || v.ValueKind != JsonValueKind.Number || !v.TryGetInt32(out int index)
                || index < (allowNone ? 0 : 1) || index >= PaintPayload.PaletteSize)
            {
                problems.Add($"{name}: '{property}' must be a palette index {(allowNone ? 0 : 1)}..{PaintPayload.PaletteSize - 1}");
                return allowNone ? 0 : 1;
            }

            return index;
        }

        private static string Painting(JsonElement e, string property, int length, string name, List<string> problems)
        {
            string pixels = Text(e, property).ToLowerInvariant();
            if (pixels.Length != 0 && pixels.Length != length)
            {
                problems.Add($"{name}: '{property}' has {pixels.Length} pixels, a painting has {length} (or none)");
                return string.Empty;
            }

            if (!PaintPayload.IsValidSymbols(pixels))
            {
                problems.Add($"{name}: '{property}' holds a symbol outside the palette (0-9, a-v)");
                return string.Empty;
            }

            return pixels;
        }
    }

    /// <summary>
    /// #2682: the seeded recolouring that makes every pioneer's skin its own — Unity-free, so the same seed gives the same
    /// pioneer on every machine. Three decisions, each by its own mix of the seed:
    /// <list type="bullet">
    /// <item><b>The garments</b>: the four hue families of the palette (red, green, blue, purple — each a dark, a mid and a
    /// light tone) are permuted, every tone onto the same tone of its new family, in the face and on every part.</item>
    /// <item><b>The skin tone</b>: the skin's own tone and its shading step along the ladder light → tan → deep (→ the dark
    /// brown as the deep tone's shade).</item>
    /// <item><b>The hair</b>: the three hair families (brown, dark, golden) rotate — in the face and the hair colour only,
    /// so a brown belt stays a brown belt.</item>
    /// </list>
    /// Transparent pixels stay transparent, every other symbol stays in the palette, the lengths never change.
    /// </summary>
    public static class PixelSkins
    {
        /// <summary>The NPC look key the server sends for a pioneer (<c>NetNpc.Look</c>).</summary>
        public const string LookKey = "pixel";

        /// <summary>The garment families (dark, mid, light).</summary>
        internal static readonly int[][] GarmentFamilies =
        {
            new[] { 22, 8, 23 },  // red
            new[] { 26, 11, 27 }, // green
            new[] { 28, 12, 29 }, // blue
            new[] { 30, 13, 31 }, // purple
        };

        /// <summary>The hair families (dark, mid, light).</summary>
        internal static readonly int[][] HairFamilies =
        {
            new[] { 19, 5, 20 },  // brown
            new[] { 16, 2, 17 },  // dark
            new[] { 24, 10, 25 }, // golden
        };

        /// <summary>The skin ladder: light, tan, deep — and the deep tone's shade.</summary>
        internal static readonly int[] SkinLadder = { 7, 6, 21, 19 };

        /// <summary>The palette symbols (index → char), the payload alphabet.</summary>
        public const string Alphabet = "0123456789abcdefghijklmnopqrstuv";

        /// <summary>A cheap, well-mixed 32-bit hash of a seed and a salt (each decision has its own).</summary>
        public static uint Mix(uint seed, uint salt)
        {
            uint x = seed * 0x9E3779B1u ^ (salt * 0x85EBCA6Bu);
            x ^= x >> 16;
            x *= 0x7FEB352Du;
            x ^= x >> 15;
            x *= 0x846CA68Bu;
            x ^= x >> 16;
            return x;
        }

        /// <summary>The skin <paramref name="source"/> recoloured by <paramref name="seed"/> (see the class summary).</summary>
        public static PixelSkin Recolour(PixelSkin source, int seed)
        {
            var garments = GarmentMap(Mix((uint)seed, 2u));
            var skin = SkinMap(source.Skin, Mix((uint)seed, 3u));
            var hair = HairMap(source.Hair, Mix((uint)seed, 4u));

            // The face: skin first, then hair, then garments (a symbol is remapped once, by the first map that knows it).
            var face = Combine(skin, hair, garments);
            var body = Combine(skin, null, garments);
            return new PixelSkin
            {
                Key = source.Key,
                Author = source.Author,
                Skin = face[source.Skin],
                Hair = source.Hair == 0 ? 0 : face[source.Hair],
                Torso = body[source.Torso],
                Arms = body[source.Arms],
                Legs = body[source.Legs],
                FacePixels = Apply(source.FacePixels, face),
                TorsoPixels = Apply(source.TorsoPixels, body),
                ArmPixels = Apply(source.ArmPixels, body),
                LegPixels = Apply(source.LegPixels, body),
                HelmetPixels = Apply(source.HelmetPixels, body),
            };
        }

        /// <summary>The garment permutation: family i → family perm[i], tone for tone.</summary>
        private static int[] GarmentMap(uint roll)
        {
            var order = new List<int> { 0, 1, 2, 3 };
            var perm = new int[order.Count];
            for (int i = 0; i < perm.Length; i++)
            {
                int pick = (int)(roll % (uint)order.Count);
                roll /= (uint)order.Count;
                perm[i] = order[pick];
                order.RemoveAt(pick);
            }

            var map = Identity();
            for (int f = 0; f < GarmentFamilies.Length; f++)
            {
                for (int t = 0; t < 3; t++)
                {
                    map[GarmentFamilies[f][t]] = GarmentFamilies[perm[f]][t];
                }
            }

            return map;
        }

        /// <summary>The skin tone: the skin's ladder step and its shade move to a new step (null when the skin is no tone of
        /// the ladder — a green alien face stays green).</summary>
        private static int[]? SkinMap(int skinIndex, uint roll)
        {
            int from = Array.IndexOf(SkinLadder, skinIndex);
            if (from < 0 || from > 2)
            {
                return null;
            }

            int to = (int)(roll % 3u);
            var map = Identity();
            map[SkinLadder[from]] = SkinLadder[to];
            if (from + 1 <= 2)
            {
                map[SkinLadder[from + 1]] = SkinLadder[Math.Min(to + 1, SkinLadder.Length - 1)];
            }

            return map;
        }

        /// <summary>The hair families rotate (null when the hair is no hair family's tone — a bald or a blue-haired one stays).</summary>
        private static int[]? HairMap(int hairIndex, uint roll)
        {
            int family = -1;
            for (int f = 0; f < HairFamilies.Length && family < 0; f++)
            {
                if (Array.IndexOf(HairFamilies[f], hairIndex) >= 0)
                {
                    family = f;
                }
            }

            if (family < 0)
            {
                return null;
            }

            int shift = (int)(roll % (uint)HairFamilies.Length);
            var map = Identity();
            for (int f = 0; f < HairFamilies.Length; f++)
            {
                int target = (f + shift) % HairFamilies.Length;
                for (int t = 0; t < 3; t++)
                {
                    map[HairFamilies[f][t]] = HairFamilies[target][t];
                }
            }

            return map;
        }

        /// <summary>One map from several: for each symbol, the first map that moves it decides (index 0 never moves).</summary>
        private static int[] Combine(int[]? first, int[]? second, int[] third)
        {
            var map = Identity();
            for (int i = 1; i < map.Length; i++)
            {
                map[i] = first is not null && first[i] != i ? first[i]
                    : second is not null && second[i] != i ? second[i]
                    : third[i];
            }

            return map;
        }

        private static int[] Identity()
        {
            var map = new int[PaintPayload.PaletteSize];
            for (int i = 0; i < map.Length; i++)
            {
                map[i] = i;
            }

            return map;
        }

        /// <summary>The painting with every symbol mapped (upper case read like lower, as the payload rules allow).</summary>
        private static string Apply(string pixels, int[] map)
        {
            if (string.IsNullOrEmpty(pixels))
            {
                return string.Empty;
            }

            var chars = new char[pixels.Length];
            for (int i = 0; i < pixels.Length; i++)
            {
                int v = Alphabet.IndexOf(char.ToLowerInvariant(pixels[i]));
                chars[i] = Alphabet[v < 0 ? 0 : map[v]];
            }

            return new string(chars);
        }
    }
