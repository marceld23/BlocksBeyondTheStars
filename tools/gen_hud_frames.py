"""The HUD frame templates (#3317, #3320): data/hud_frames.json.

A HUD frame is what a player paints in the character editor's HUD mode: four 32x32 tiles of the pixel editor's palette
(one base32 symbol per pixel, row 0 = top, "0" = transparent) - the top-left CORNER (mirrored into the other three
corners), the TOP edge, the left SIDE edge (mirrored to the right) and the BOTTOM edge, each repeated along the screen -
plus the palette indices that TWINKLE (their pixels cycle through twinkleColors about twice a second). The game lays the
tiles out exactly as preview() does here (src/BlocksBeyondTheStars.Client.Core/HudFrames/HudFrameLayout.cs).

Templates are starting points: putting one on copies it into the player's own frame. "unlock": "" is free for everybody,
"calendar" only once a festival calendar door unlocked it in that world (hudframe:<key>, #3315).

Usage (from the repository root, no dependencies):

    uv run --no-project python tools/gen_hud_frames.py
        Rebuilds the generated templates (deterministic) and keeps every adopted frame already in the file.

    uv run --no-project python tools/gen_hud_frames.py --preview <dir>
        Also writes <dir>/hud_frame_<key>.png: each template on a dark 960x540 screen with a hinted hotbar.

    uv run --no-project python tools/gen_hud_frames.py --from-hud <hud.json> --key <key> [--unlock calendar]
        Adopts a submitted frame (unpacked by `tools/pull_submissions.py --kind hud --fetch`, #3319). Look at it first
        (--preview), then add hudframe.<key>.name to data/locales/en.json and de.json - never copy the player's own name.

    uv run --no-project python tools/gen_hud_frames.py --check
        Validates the file (the same rules as HudFrameTemplatesTests).

The Christmas lights: red is an ACCENT here - it is the enemies' colour in this game - so the bulbs are warm white,
gold, green, blue and purple pixels whose twinkle merely passes through a soft red now and then.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import struct
import sys
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FRAMES = REPO / "data" / "hud_frames.json"

ALPHABET = "0123456789abcdefghijklmnopqrstuv"
SIZE = 32
KEY_RE = re.compile(r"^[a-z0-9_]{1,64}$")
COLOR_RE = re.compile(r"^#[0-9a-fA-F]{6}$")

# The pixel editor's palette (client FacePalette.Colors) - index 0 is transparent.
PALETTE = [
    None,
    (20, 18, 24), (74, 64, 78), (150, 150, 158), (240, 240, 236), (120, 72, 40), (214, 160, 110), (247, 206, 170),
    (196, 60, 50), (232, 150, 64), (238, 206, 76), (96, 176, 90), (70, 150, 210), (150, 96, 200), (240, 150, 190),
    (60, 200, 200), (46, 44, 54), (104, 100, 112), (198, 198, 204), (70, 40, 22), (176, 122, 74), (150, 96, 58),
    (120, 30, 28), (236, 122, 104), (168, 92, 26), (250, 226, 150), (48, 110, 56), (158, 214, 120), (34, 84, 140),
    (148, 202, 240), (92, 52, 132), (206, 166, 236),
]

# Palette indices by name.
NEAR_BLACK, SLATE, GREY, WHITE = 1, 2, 3, 4
RED, ORANGE, YELLOW, GREEN, BLUE, PURPLE = 8, 9, 10, 11, 12, 13
CHARCOAL, MID_GREY, LIGHT_GREY = 16, 17, 18
DARK_RED, DARK_ORANGE, LIGHT_YELLOW, DARK_GREEN, LIGHT_GREEN = 22, 24, 25, 26, 27
DARK_BLUE, LIGHT_BLUE, LIGHT_PURPLE = 28, 29, 31

HEADER = """// HUD frame templates (#3317, #3320) - GENERATED by tools/gen_hud_frames.py (deterministic); adopted player frames are
// kept by the generator. Four 32 x 32 tiles of pixel-editor palette indices (base32, one char per pixel, row 0 = top,
// 0 = transparent; an empty tile is transparent): the top-left corner (mirrored to the other corners), the top edge, the
// left side edge (mirrored to the right) and the bottom edge, each repeated along the screen. "twinkle": the palette
// indices whose pixels cycle through "twinkleColors" (#rrggbb) about twice a second. "unlock": "" = free, "calendar" =
// once a festival calendar door unlocked it in this world (hudframe:<key>). Names: hudframe.<key>.name in data/locales.
"""


def blank():
    return [[0] * SIZE for _ in range(SIZE)]


def put(grid, x, y, index):
    if 0 <= x < SIZE and 0 <= y < SIZE:
        grid[y][x] = index


def encode(grid):
    return "".join(ALPHABET[v] for row in grid for v in row)


def decode(text):
    if not text:
        return blank()
    return [[ALPHABET.index(text[y * SIZE + x].lower()) for x in range(SIZE)] for y in range(SIZE)]


def noise(x, y, salt):
    """A deterministic 0..255 hash of a cell - the generator's only 'randomness'."""
    h = (x * 374761393 + y * 668265263 + salt * 2246822519) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return (h ^ (h >> 16)) & 0xFF


# ---------------------------------------------------------------- Christmas lights (calendar)

LIGHTS = [LIGHT_YELLOW, LIGHT_GREEN, YELLOW, LIGHT_BLUE, LIGHT_PURPLE]  # bulb pixels: the twinkling indices
LIGHT_COLORS = ["#fff4d6", "#7cff8a", "#ffd34d", "#6cc8ff", "#ff7a7a"]  # warm white, green, gold, blue, a little red


def garland_centre_row(x):
    """The top garland's centre line: a gentle wave with the tile's period, so it runs on seamlessly."""
    return 5 + round(1.2 * math.sin(2 * math.pi * x / SIZE))


def garland_centre_col(y):
    """The side garland's centre line (slimmer, the same idea turned on its side)."""
    return 3 + round(0.8 * math.sin(2 * math.pi * y / SIZE))


def fir_across(grid, x, centre, half, salt):
    """One column of a fir garland lying along the top: dark green with lighter needles, jagged edges, a dusting of snow."""
    top = centre - half - (1 if noise(x, 0, salt) > 170 else 0)
    bottom = centre + half + (noise(x, 1, salt) % 3)
    for y in range(max(0, top), bottom + 1):
        put(grid, x, y, GREEN if noise(x, y, salt + 7) > 175 else DARK_GREEN)
    if noise(x, 2, salt) > 120:
        put(grid, x, max(0, top), WHITE if noise(x, 3, salt) > 90 else LIGHT_GREY)  # snow resting on the branches


def fir_down(grid, y, centre, half, salt):
    """One row of the slimmer garland hanging down the side."""
    left = centre - half
    right = centre + half + (noise(4, y, salt) % 2)
    for x in range(max(0, left), right + 1):
        put(grid, x, y, GREEN if noise(x, y, salt + 9) > 180 else DARK_GREEN)
    if noise(5, y, salt) > 150:
        put(grid, max(0, left), y, LIGHT_GREY)


SIDE_WIRE = 8  # the side light string's column


def wire_row(x):
    """The light string's swag under the top garland: low in the tile's middle, high at its ends (seamless)."""
    return 12 + round(3 * math.sin(math.pi * x / SIZE))


def bulb_down(grid, x, wire, light):
    """A bulb hanging under the wire: a dark cap, then a 2 x 3 glass of one twinkling index."""
    put(grid, x, wire + 1, SLATE)
    put(grid, x + 1, wire + 1, SLATE)
    for dy in range(2, 5):
        put(grid, x, wire + dy, light)
        put(grid, x + 1, wire + dy, light)


def bulb_right(grid, y, wire, light):
    """A bulb pointing right off the side wire."""
    put(grid, wire + 1, y, SLATE)
    put(grid, wire + 1, y + 1, SLATE)
    for dx in range(2, 5):
        put(grid, wire + dx, y, light)
        put(grid, wire + dx, y + 1, light)


def snowflake(grid, x, y, big=False):
    """A small six-armed flake: white heart, light grey arms (two cells long when big)."""
    put(grid, x, y, WHITE)
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        put(grid, x + dx, y + dy, LIGHT_GREY)
        if big:
            put(grid, x + 2 * dx, y + 2 * dy, WHITE)
    if big:
        for dx, dy in ((1, 1), (-1, -1), (1, -1), (-1, 1)):
            put(grid, x + dx, y + dy, LIGHT_GREY)


def christmas_top():
    grid = blank()
    for x in range(SIZE):
        fir_across(grid, x, garland_centre_row(x), 3, salt=1)
    for x in range(SIZE):
        if grid[wire_row(x)][x] == 0:
            put(grid, x, wire_row(x), CHARCOAL)
    for i, x in enumerate((2, 8, 14, 20, 26)):
        bulb_down(grid, x, wire_row(x), LIGHTS[i])
    return grid


def christmas_side():
    grid = blank()
    for y in range(SIZE):
        fir_down(grid, y, garland_centre_col(y), 2, salt=3)
    for y in range(SIZE):
        if grid[y][SIDE_WIRE] == 0:
            put(grid, SIDE_WIRE, y, CHARCOAL)
    for i, y in enumerate((3, 14, 25)):
        bulb_right(grid, y, SIDE_WIRE, LIGHTS[(i + 2) % len(LIGHTS)])
    # A blue bauble on a thread (a calm accent between the lights), hanging off the garland.
    for x in range(6, 10):
        put(grid, x, 19, GREY)
    for dx, dy, index in ((0, 0, BLUE), (1, 0, WHITE), (-1, 1, DARK_BLUE), (0, 1, BLUE), (1, 1, BLUE), (2, 1, BLUE),
                          (0, 2, DARK_BLUE), (1, 2, BLUE)):
        put(grid, 10 + dx, 19 + dy, index)  # the white pixel is its glint
    return grid


def christmas_corner():
    grid = blank()
    # The two garlands meet in the corner: the top one runs out to the right, the side one runs down.
    for x in range(SIZE):
        fir_across(grid, x, garland_centre_row(x), 3, salt=1)
    for y in range(11, SIZE):
        fir_down(grid, y, garland_centre_col(y), 2, salt=3)
    # The lights run out of the corner: along the top from x = 17, down the side from y = 17.
    for x in range(17, SIZE):
        if grid[wire_row(x)][x] == 0:
            put(grid, x, wire_row(x), CHARCOAL)
    for i, x in ((3, 20), (4, 26)):
        bulb_down(grid, x, wire_row(x), LIGHTS[i])
    for y in range(17, SIZE):
        if grid[y][SIDE_WIRE] == 0:
            put(grid, SIDE_WIRE, y, CHARCOAL)
    bulb_right(grid, 25, SIDE_WIRE, LIGHTS[(2 + 2) % len(LIGHTS)])  # the side tile's bulb pattern, continued
    # A heap of snow on the corner where the two garlands cross.
    for y in range(13):
        for x in range(17):
            d = math.hypot(x / 16.0, y / 12.0)
            if d < 1.0 - (noise(x, y, 11) % 3) * 0.03:
                put(grid, x, y, LIGHT_GREY if d > 0.84 or noise(x, y, 12) > 225 else WHITE)
    # A red bow on the snow - the one red of the frame (red is the enemies' colour: an accent only).
    for x, y in ((12, 11), (13, 11), (12, 12), (14, 12), (12, 13), (13, 13),
                 (17, 11), (18, 11), (16, 12), (18, 12), (17, 13), (18, 13)):
        put(grid, x, y, RED)
    for x, y in ((15, 12), (14, 14), (13, 15), (16, 14), (17, 15)):
        put(grid, x, y, DARK_RED)
    # Snowflakes drifting towards the middle of the view (the inner part of the tile stays mostly clear).
    snowflake(grid, 23, 23, big=True)
    snowflake(grid, 15, 27)
    snowflake(grid, 29, 29)
    snowflake(grid, 14, 21)
    return grid


def christmas_bottom():
    """Only a thin line of snow: the hotbar lives at the bottom of the screen."""
    grid = blank()
    for x in range(SIZE):
        height = 1 + round(0.9 * (1 + math.sin(2 * math.pi * x / SIZE + 1.3)))  # 1..3 rows, seamless
        for y in range(SIZE - height, SIZE):
            put(grid, x, y, LIGHT_GREY if y == SIZE - height else WHITE)
    return grid


# ---------------------------------------------------------------- the visor rim (free)

RIM = [CHARCOAL, MID_GREY, LIGHT_GREY, GREY, SLATE]  # outside -> inside: shell edge, metal, highlight, metal, shadow
RIM_RADIUS = 12


def rim_color(depth):
    """The rim's colour at a depth (pixels in from the screen edge); None inside the view."""
    if depth < 0:
        return CHARCOAL  # the helmet shell beyond the rounded rim
    return RIM[depth] if depth < len(RIM) else None


def visor_corner():
    grid = blank()
    for y in range(SIZE):
        for x in range(SIZE):
            if x < RIM_RADIUS and y < RIM_RADIUS:
                depth = math.floor(RIM_RADIUS - math.hypot(RIM_RADIUS - x - 0.5, RIM_RADIUS - y - 0.5))
            else:
                depth = min(x, y)
            color = rim_color(depth)
            if color is not None:
                put(grid, x, y, color)
    put(grid, 20, 2, WHITE)  # a rivet on the rim
    put(grid, 2, 20, WHITE)
    return grid


def visor_top():
    grid = blank()
    for x in range(SIZE):
        for depth, color in enumerate(RIM):
            put(grid, x, depth, color)
    put(grid, 16, 2, WHITE)  # one rivet per tile
    return grid


def visor_side():
    grid = blank()
    for y in range(SIZE):
        for depth, color in enumerate(RIM):
            put(grid, depth, y, color)
    put(grid, 2, 16, WHITE)
    return grid


def visor_bottom():
    """The chin of the rim: the same profile as the top, the darkest row at the very bottom, so it meets the mirrored
    corners without a step."""
    grid = blank()
    for x in range(SIZE):
        for depth, color in enumerate(RIM):
            put(grid, x, SIZE - 1 - depth, color)
    return grid


# ---------------------------------------------------------------- starlight (free)

STARS = [LIGHT_YELLOW, LIGHT_BLUE, LIGHT_PURPLE]
STAR_COLORS = ["#ffffff", "#fff2b0", "#bfe0ff"]


def star(grid, x, y, light, big=False):
    put(grid, x, y, light)
    if big:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            put(grid, x + dx, y + dy, light)
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
            put(grid, x + dx, y + dy, DARK_BLUE)


def starlight(positions, band):
    grid = blank()
    for x, y in band:
        put(grid, x, y, DARK_BLUE)
    for i, (x, y, big) in enumerate(positions):
        star(grid, x, y, STARS[i % len(STARS)], big)
    return grid


def stars_templates():
    top_band = [(x, 0) for x in range(SIZE)] + [(x, 1) for x in range(SIZE) if noise(x, 1, 21) > 110]
    side_band = [(0, y) for y in range(SIZE)] + [(1, y) for y in range(SIZE) if noise(1, y, 22) > 110]
    corner = starlight([(6, 6, True), (14, 3, False), (3, 14, False), (19, 8, False), (9, 18, False), (24, 4, True),
                        (4, 25, True)], top_band + side_band)
    top = starlight([(5, 4, False), (12, 7, True), (21, 3, False), (27, 9, False)], top_band)
    side = starlight([(4, 5, False), (7, 13, True), (3, 21, False), (9, 28, False)], side_band)
    bottom = starlight([(8, 30, False), (23, 29, False)], [(x, 31) for x in range(SIZE)])
    return corner, top, side, bottom


# ---------------------------------------------------------------- the file

def generated():
    corner, top, side, bottom = stars_templates()
    return [
        frame("visor", "", visor_corner(), visor_top(), visor_side(), visor_bottom(), [], []),
        frame("stars", "", corner, top, side, bottom, STARS, STAR_COLORS),
        frame("christmas_lights", "calendar", christmas_corner(), christmas_top(), christmas_side(), christmas_bottom(),
              LIGHTS, LIGHT_COLORS),
    ]


def frame(key, unlock, corner, top, side, bottom, twinkle, colors):
    return {
        "key": key,
        "unlock": unlock,
        "corner": encode(corner),
        "top": encode(top),
        "side": encode(side),
        "bottom": encode(bottom),
        "twinkle": list(twinkle),
        "twinkleColors": list(colors),
    }


def strip_comments(text):
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("//"))


def load_frames():
    if not FRAMES.exists():
        return []
    return json.loads(strip_comments(FRAMES.read_text(encoding="utf-8"))).get("frames", [])


def write_frames(frames):
    lines = [HEADER.rstrip("\n"), "{", '  "frames": [']
    for i, f in enumerate(frames):
        body = ",\n".join(f'      "{name}": {json.dumps(f.get(name, default), ensure_ascii=False)}'
                          for name, default in (("key", ""), ("unlock", ""), ("corner", ""), ("top", ""), ("side", ""),
                                                ("bottom", ""), ("twinkle", []), ("twinkleColors", [])))
        lines.append("    {\n" + body + "\n    }" + ("," if i < len(frames) - 1 else ""))
    lines += ["  ]", "}"]
    FRAMES.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def problems(f):
    """What is wrong with one frame entry (the rules of HudFrameDesign.TryFromTemplate)."""
    found = []
    if not KEY_RE.match(f.get("key", "")):
        found.append("bad key")
    if f.get("unlock", "") not in ("", "calendar"):
        found.append("unlock must be '' or 'calendar'")
    for name in ("corner", "top", "side", "bottom"):
        tile = f.get(name, "")
        if tile and (len(tile) != SIZE * SIZE or any(c.lower() not in ALPHABET for c in tile)):
            found.append(f"{name}: not 1024 palette symbols")
    twinkle = f.get("twinkle", [])
    if len(twinkle) > 8 or len(set(twinkle)) != len(twinkle) or any(not isinstance(i, int) or not 1 <= i <= 31 for i in twinkle):
        found.append("twinkle: at most 8 distinct indices 1..31")
    colors = f.get("twinkleColors", [])
    if len(colors) > 8 or any(not COLOR_RE.match(c or "") for c in colors):
        found.append("twinkleColors: at most 8 #rrggbb")
    if all(set(f.get(name, "") or "0") == {"0"} for name in ("corner", "top", "side", "bottom")):
        found.append("the frame paints nothing")
    return found


# ---------------------------------------------------------------- preview (the game's 9-slice layout)

def tile_pixels(width, height, size):
    short = max(1, min(width, height))
    medium = max(1, math.floor(short / 360 + 0.5))
    if size <= 0:
        scale = max(1, math.floor(short / 540 + 0.5))
    elif size >= 2:
        scale = max(medium + 1, math.floor(short / 270 + 0.5))
    else:
        scale = medium
    return SIZE * min(scale, max(1, short // (3 * SIZE)))


def layout(width, height, tile):
    """(tile name, x, y, w, h, flip_x, flip_y, repeat_x, repeat_y) - HudFrameLayout.Compute with no inset."""
    t = min(tile, min(width, height) / 2)
    edge_w, edge_h = width - 2 * t, height - 2 * t

    def repeats(length):
        return 0 if length <= 0 else max(1, math.floor(length / t + 0.5))

    across, down = repeats(edge_w), repeats(edge_h)
    right, bottom = width - t, height - t
    return [
        ("corner", 0, 0, t, t, False, False, 1, 1), ("corner", right, 0, t, t, True, False, 1, 1),
        ("corner", 0, bottom, t, t, False, True, 1, 1), ("corner", right, bottom, t, t, True, True, 1, 1),
        ("top", t, 0, edge_w, t, False, False, across, 1), ("bottom", t, bottom, edge_w, t, False, False, across, 1),
        ("side", 0, t, t, edge_h, False, False, 1, down), ("side", right, t, t, edge_h, True, False, 1, down),
    ]


def preview(f, width=960, height=540, background=(20, 28, 42)):
    """The frame on a dark screen with a hinted hotbar, as RGB rows (twinkle at its first step)."""
    pixels = [[list(background) for _ in range(width)] for _ in range(height)]
    for i in range(9):  # the hotbar the bottom edge must leave readable
        x0 = (width - 9 * 44) // 2 + i * 44
        for y in range(height - 54, height - 14):
            for x in range(x0, x0 + 40):
                pixels[y][x] = [60, 120, 150] if y in (height - 54, height - 15) or x in (x0, x0 + 39) else [26, 40, 56]
    colors = {}
    for slot, index in enumerate(f.get("twinkle", [])):
        hex_list = f.get("twinkleColors") or ["#fff4d6"]
        value = hex_list[slot % len(hex_list)]
        colors[index] = tuple(int(value[k:k + 2], 16) for k in (1, 3, 5))
    grids = {name: decode(f.get(name, "")) for name in ("corner", "top", "side", "bottom")}
    for name, px, py, pw, ph, fx, fy, rx, ry in layout(width, height, tile_pixels(width, height, 1)):
        if pw <= 0 or ph <= 0:
            continue
        for y in range(round(py), round(py + ph)):
            v = (y + 0.5 - py) / ph * ry
            row = min(SIZE - 1, int((v - math.floor(v)) * SIZE))
            row = SIZE - 1 - row if fy else row
            for x in range(round(px), round(px + pw)):
                u = (x + 0.5 - px) / pw * rx
                col = min(SIZE - 1, int((u - math.floor(u)) * SIZE))
                col = SIZE - 1 - col if fx else col
                index = grids[name][row][col]
                if index:
                    pixels[y][x] = list(colors.get(index, PALETTE[index]))
    return pixels


def write_png(path, pixels):
    height, width = len(pixels), len(pixels[0])
    raw = b"".join(b"\x00" + bytes(c for px in row for c in px) for row in pixels)

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    Path(path).write_bytes(png)


# ---------------------------------------------------------------- main

def adopt(frames, path, key, unlock):
    hud = json.loads(Path(path).read_text(encoding="utf-8"))
    entry = frame(key, unlock, decode(hud.get("corner", "")), decode(hud.get("top", "")), decode(hud.get("side", "")),
                  decode(hud.get("bottom", "")), hud.get("twinkle", []), hud.get("twinkleColors", []))
    found = problems(entry)
    if found:
        sys.exit(f"{path}: " + "; ".join(found))
    return [f for f in frames if f.get("key") != key] + [entry]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--preview", type=Path, help="also write a preview PNG per template into this folder")
    parser.add_argument("--from-hud", type=Path, help="adopt a submitted hud.json")
    parser.add_argument("--key", help="the adopted frame's key (with --from-hud)")
    parser.add_argument("--unlock", default="", choices=("", "calendar"), help="the adopted frame's unlock (with --from-hud)")
    parser.add_argument("--check", action="store_true", help="only validate data/hud_frames.json")
    args = parser.parse_args(argv)

    existing = load_frames()
    if args.check:
        bad = [(f.get("key", "?"), p) for f in existing for p in problems(f)]
        for key, p in bad:
            print(f"{key}: {p}")
        sys.exit(1 if bad else 0)

    made = generated()
    made_keys = {f["key"] for f in made}
    frames = made + [f for f in existing if f.get("key") not in made_keys]  # adopted frames stay
    if args.from_hud:
        if not args.key or not KEY_RE.match(args.key):
            sys.exit("--from-hud needs --key <lower_case_key>")
        frames = adopt(frames, args.from_hud, args.key, args.unlock)
    for f in frames:
        found = problems(f)
        if found:
            sys.exit(f"{f.get('key')}: " + "; ".join(found))
    write_frames(frames)
