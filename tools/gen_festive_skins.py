"""The festive character skins (#3321): data/skins.json.

A skin template is exactly what a player paints in the game's Appearance editor — the four appearance colours and the
body paintings of torso, arms, legs and helmet (BodyPaint, #874): concatenated 32x32 chunks of palette indices, one base32
symbol per pixel ("0" = transparent, row 0 = the top of the chunk). The chunks and their order are the editor's:

    torso   4 chunks: front | left | back | right                 (the figure's own left and right)
    arms    8 chunks: left arm front | outer | back | inner, then the right arm's four
    legs    8 chunks: the same as the arms
    helmet  5 chunks: left | back | right | chin | top           (the front is open, the face shows)

On the avatar every side chunk spans its part's whole height: the torso's row 0 is the collar and rows ~23-31 the pelvis,
an arm's rows 22-26 are the cuff and 27-31 the hand, a leg's rows 28-31 the foot. The helmet's side chunks have the face
at their front edge (left: column 0, right: column 31) and the bars' front lips continue those columns round the face;
the top chunk's row 0 is the back of the head, row 31 the forehead; the chin chunk's row 0 is its front.

"colors" are skin, torso, arms, legs as #rrggbb ("" keeps the player's own skin colour, so the face stays theirs).

The Christmas outfit (unlocked by door 6 of the Advent calendar): green, white and gold with red only as small accents —
red is the enemies' colour in this game. A green coat with white fur at the collar and hem, a gold belt with a gold
buckle and a row of small red buttons; green sleeves with white fur cuffs and a thin red stripe; dark green trousers in
dark boots with white fur tops and little gold buckles; a green hood with a white fur band round the face, a small gold
star on the back and a tiny red pompom on top.

Usage (from the repository root, no dependencies):

    uv run --no-project python tools/gen_festive_skins.py [--preview <dir>]
        Rebuilds the generated skins in data/skins.json (deterministic; every other skin in the file is kept) and, with
        --preview, writes a PNG of every chunk, every part's canvas and an overview sheet into <dir>.

    uv run --no-project python tools/gen_festive_skins.py --check
        Validates the file (payload lengths and symbols, colours).
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import sys
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKINS = REPO / "data" / "skins.json"

ALPHABET = "0123456789abcdefghijklmnopqrstuv"
SIZE = 32
PARTS = ("torso", "arms", "legs", "helmet")
CHUNKS = {"torso": 4, "arms": 8, "legs": 8, "helmet": 5}
COLUMNS = {"torso": 4, "arms": 4, "legs": 4, "helmet": 5}

HEADER = [
    "// Character skin templates (#3321): the four appearance colours (skin, torso, arms, legs as #rrggbb; \"\" keeps the",
    "// player's own) and the body paint of torso, arms, legs and helmet - the character editor's payloads (32 x 32 chunks of",
    "// base32 palette symbols, row 0 = top, 0 = transparent). \"unlock\": \"\" = free, \"calendar\" = once a festival calendar",
    "// door unlocked it in this world (skin:<key>). Generated by tools/gen_festive_skins.py - edit the script, not this file.",
]

# The face/body-paint palette (client FacePalette.Colors) — index 0 is transparent.
PALETTE = [
    None,
    (20, 18, 24), (74, 64, 78), (150, 150, 158), (240, 240, 236), (120, 72, 40), (214, 160, 110), (247, 206, 170),
    (196, 60, 50), (232, 150, 64), (238, 206, 76), (96, 176, 90), (70, 150, 210), (150, 96, 200), (240, 150, 190),
    (60, 200, 200), (46, 44, 54), (104, 100, 112), (198, 198, 204), (70, 40, 22), (176, 122, 74), (150, 96, 58),
    (120, 30, 28), (236, 122, 104), (168, 92, 26), (250, 226, 150), (48, 110, 56), (158, 214, 120), (34, 84, 140),
    (148, 202, 240), (92, 52, 132), (206, 166, 236),
]

NEARBLACK, WHITE, RED, YELLOW, GREEN = 1, 4, 8, 10, 11
CHARCOAL, MIDGREY, LIGHTGREY, DARKBROWN = 16, 17, 18, 19
DARKRED, LIGHTRED, DARKORANGE, LIGHTYELLOW, DARKGREEN = 22, 23, 24, 25, 26

# The outfit's colours by role.
COAT = DARKGREEN
COAT_SHADE = CHARCOAL
COAT_LIGHT = GREEN
FUR = WHITE
FUR_SHADE = LIGHTGREY
GOLD = YELLOW
GOLD_EDGE = DARKORANGE
GOLD_LIGHT = LIGHTYELLOW
BOOT = CHARCOAL
BOOT_SOLE = NEARBLACK
GLOVE = CHARCOAL

FRONT, LEFT, BACK, RIGHT = 0, 1, 2, 3        # torso chunks
L_FRONT, L_OUTER, L_BACK, L_INNER = 0, 1, 2, 3  # a limb's chunks
H_LEFT, H_BACK, H_RIGHT, H_CHIN, H_TOP = 0, 1, 2, 3, 4  # helmet chunks

# A small five-pointed star, 9 x 9 ("#" gold, "+" the light centre).
STAR = [
    "....#....",
    "....#....",
    "...#+#...",
    "#########",
    ".###+###.",
    "..#####..",
    "..##.##..",
    ".##...##.",
    ".#.....#.",
]


class Grid:
    """A palette-index canvas, row 0 at the top."""

    def __init__(self, w: int = SIZE, h: int = SIZE, fill: int = 0) -> None:
        self.w, self.h = w, h
        self.px = [[fill] * w for _ in range(h)]

    def set(self, x: int, y: int, c: int) -> None:
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y][x] = c

    def rect(self, x0: int, y0: int, x1: int, y1: int, c: int) -> None:
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, c)

    def outline(self, x0: int, y0: int, x1: int, y1: int, c: int) -> None:
        for x in range(x0, x1 + 1):
            self.set(x, y0, c)
            self.set(x, y1, c)
        for y in range(y0, y1 + 1):
            self.set(x0, y, c)
            self.set(x1, y, c)

    def encode(self) -> str:
        return "".join(ALPHABET[c] for row in self.px for c in row)


# ---------------------------------------------------------------- motifs


def fur(g: Grid, x0: int, y0: int, x1: int, y1: int) -> None:
    """White fur: white with a soft grey fleck pattern (fixed, so the file never changes between runs)."""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            fleck = (x * 3 + y * 5) % 7 == 0 or (x * 5 + y * 2) % 11 == 0
            g.set(x, y, FUR_SHADE if fleck else FUR)


def belt(g: Grid, y0: int, y1: int) -> None:
    """A gold belt with darker gold edges."""
    g.rect(0, y0, 31, y1, GOLD)
    g.rect(0, y0, 31, y0, GOLD_EDGE)
    g.rect(0, y1, 31, y1, GOLD_EDGE)
    for x in range(2, 32, 6):
        g.set(x, y0 + 1, GOLD_LIGHT)  # a glint now and then


def buckle(g: Grid, x0: int, y0: int) -> None:
    """The belt's buckle: an 8 x 6 gold frame round a dark strap, a light glint top left."""
    g.rect(x0, y0, x0 + 7, y0 + 5, GOLD)
    g.outline(x0, y0, x0 + 7, y0 + 5, GOLD_EDGE)
    g.rect(x0 + 2, y0 + 2, x0 + 5, y0 + 3, DARKBROWN)
    g.set(x0 + 1, y0 + 1, GOLD_LIGHT)
    g.set(x0 + 2, y0 + 1, GOLD_LIGHT)


def button(g: Grid, x: int, y: int) -> None:
    """A small red button (2 x 2) with a highlight and a shadow — the outfit's red accent."""
    g.set(x, y, LIGHTRED)
    g.set(x + 1, y, RED)
    g.set(x, y + 1, RED)
    g.set(x + 1, y + 1, DARKRED)


def star(g: Grid, x0: int, y0: int) -> None:
    for dy, row in enumerate(STAR):
        for dx, ch in enumerate(row):
            if ch == "#":
                g.set(x0 + dx, y0 + dy, GOLD)
            elif ch == "+":
                g.set(x0 + dx, y0 + dy, GOLD_LIGHT)


def pompom(g: Grid, x0: int, y0: int) -> None:
    """A tiny round red pompom (4 x 4, corners cut) — the hood's only red."""
    g.rect(x0 + 1, y0, x0 + 2, y0 + 3, RED)
    g.rect(x0, y0 + 1, x0 + 3, y0 + 2, RED)
    g.set(x0 + 1, y0 + 1, LIGHTRED)
    g.set(x0 + 2, y0 + 3, DARKRED)
    g.set(x0 + 3, y0 + 2, DARKRED)


# ---------------------------------------------------------------- the Christmas outfit


def coat_torso(side: int) -> Grid:
    """The coat: fur collar (rows 0-3), green coat, gold belt (rows 20-23), coat skirt, fur hem over the hips (28-31)."""
    g = Grid(fill=COAT)
    fur(g, 0, 0, 31, 3)
    g.rect(0, 4, 31, 4, FUR_SHADE)  # the collar's soft shadow
    belt(g, 20, 23)
    fur(g, 0, 28, 31, 31)
    g.rect(0, 27, 31, 27, COAT_SHADE)  # the skirt's shadow over the hem
    if side == FRONT:
        g.rect(15, 5, 16, 19, COAT_LIGHT)  # the coat's placket
        g.rect(15, 24, 16, 26, COAT_LIGHT)
        for y in (7, 11, 15):
            button(g, 15, y)
        buckle(g, 12, 19)
    elif side in (LEFT, RIGHT):
        for y in range(6, 27, 4):
            if not 20 <= y <= 23:
                g.set(15, y, COAT_SHADE)  # a faint side seam (the arm hides most of it)
    return g


def sleeve(face: int) -> Grid:
    """A green sleeve, a thin red stripe down the outer side, white fur cuffs (rows 22-26), dark gloves (27-31)."""
    g = Grid(fill=COAT)
    if face == L_INNER:
        for y in range(0, 22, 4):
            g.set(15, y, COAT_SHADE)  # a faint inner seam
    if face == L_OUTER:
        g.rect(15, 2, 15, 21, RED)
        g.rect(16, 2, 16, 21, DARKRED)
    g.rect(0, 0, 31, 0, COAT_LIGHT)  # the shoulder seam catching the light
    fur(g, 0, 22, 31, 26)
    g.rect(0, 27, 31, 31, GLOVE)
    g.rect(0, 27, 31, 27, NEARBLACK)
    if face == L_FRONT:
        g.rect(10, 29, 21, 29, MIDGREY)  # the knuckles' sheen
    return g


def trouser_leg(face: int) -> Grid:
    """Dark green trousers, white fur boot tops (rows 18-21), dark boots with a little gold buckle, black soles."""
    g = Grid(fill=COAT)
    if face == L_INNER:
        for y in range(1, 18, 4):
            g.set(15, y, COAT_SHADE)  # a faint inner seam
    if face == L_OUTER:
        g.rect(15, 0, 15, 17, COAT_LIGHT)  # the outer seam catching the light
    fur(g, 0, 18, 31, 21)
    g.rect(0, 22, 31, 30, BOOT)
    g.rect(0, 22, 31, 22, MIDGREY)  # the boot top's rim
    g.rect(0, 31, 31, 31, BOOT_SOLE)
    if face == L_FRONT:
        g.rect(13, 25, 18, 27, GOLD)
        g.outline(13, 25, 18, 27, GOLD_EDGE)
        g.set(14, 26, GOLD_LIGHT)
        g.rect(11, 30, 20, 30, MIDGREY)  # the toe cap's sheen
    return g


def hood(chunk: int) -> Grid:
    """The hood: green, a white fur band at the top of the sides and back (rows 0-5) that meets the fur round the face
    (the side chunks' front columns, the chin's front rows, the top's front rows), a gold star on the back, a tiny red
    pompom on top."""
    g = Grid(fill=COAT)
    if chunk in (H_LEFT, H_BACK, H_RIGHT):
        fur(g, 0, 0, 31, 5)
        g.rect(0, 6, 31, 6, FUR_SHADE)
        g.rect(0, 31, 31, 31, COAT_SHADE)  # the hood's lower edge
    if chunk == H_LEFT:
        fur(g, 0, 0, 3, 31)  # the face is at column 0
    elif chunk == H_RIGHT:
        fur(g, 28, 0, 31, 31)  # the face is at column 31
    elif chunk == H_BACK:
        star(g, 11, 11)
    elif chunk == H_CHIN:
        fur(g, 0, 0, 31, 5)  # the chin's front edge (row 0) frames the face from below
    elif chunk == H_TOP:
        fur(g, 0, 26, 31, 31)  # the forehead (row 31 is the front)
        g.rect(0, 25, 31, 25, FUR_SHADE)
        for y in range(2, 24, 5):
            g.set(8, y, COAT_LIGHT)  # the hood's soft folds
            g.set(23, y + 2, COAT_LIGHT)
        pompom(g, 14, 9)
    return g


def strip(chunks: list[Grid]) -> str:
    """A part payload: the chunks one after another, each row-major from its top."""
    return "".join(g.encode() for g in chunks)


def christmas() -> tuple[dict, dict[str, list[Grid]]]:
    parts = {
        "torso": [coat_torso(side) for side in (FRONT, LEFT, BACK, RIGHT)],
        "arms": [sleeve(face) for _limb in range(2) for face in range(4)],
        "legs": [trouser_leg(face) for _limb in range(2) for face in range(4)],
        "helmet": [hood(chunk) for chunk in range(5)],
    }
    r, gr, b = PALETTE[COAT]
    green = f"#{r:02x}{gr:02x}{b:02x}"
    skin = {
        "key": "christmas",
        "unlock": "calendar",
        "colors": ["", green, green, green],
        "paint": [strip(parts[name]) for name in PARTS],
    }
    return skin, parts


def generated() -> list[tuple[dict, dict[str, list[Grid]]]]:
    return [christmas()]


# ---------------------------------------------------------------- the file


def load(path: Path = SKINS) -> dict:
    if not path.exists():
        return {"skins": []}
    text = "\n".join(line for line in path.read_text(encoding="utf-8").splitlines() if not line.lstrip().startswith("//"))
    return json.loads(text)


def write(skins: list[dict], path: Path = SKINS) -> None:
    lines = HEADER + ["{", '  "skins": [']
    for i, s in enumerate(skins):
        body = json.dumps(s, ensure_ascii=False, separators=(", ", ": "))
        lines.append("    " + body + ("," if i < len(skins) - 1 else ""))
    lines += ["  ]", "}", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def validate(data: dict) -> list[str]:
    problems: list[str] = []
    keys = set()
    for s in data.get("skins", []):
        key = s.get("key", "")
        if not key or key in keys:
            problems.append(f"skin key missing or twice: {key!r}")
        keys.add(key)
        colors = s.get("colors", [])
        if len(colors) not in (0, 4) or any(c and not re.fullmatch(r"#[0-9a-f]{6}", c) for c in colors):
            problems.append(f"{key}: colors must be four #rrggbb (or \"\") — got {colors}")
        paint = s.get("paint", [])
        if len(paint) not in (0, 4):
            problems.append(f"{key}: paint must name all four parts — got {len(paint)}")
        for name, payload in zip(PARTS, paint):
            if payload and len(payload) != CHUNKS[name] * SIZE * SIZE:
                problems.append(f"{key}: {name} is {len(payload)} symbols, not {CHUNKS[name] * SIZE * SIZE}")
            if payload and not set(payload) <= set(ALPHABET):
                problems.append(f"{key}: {name} holds symbols outside the palette alphabet")
    return problems


# ---------------------------------------------------------------- previews


def png(path: Path, pixels: list[list[tuple[int, int, int, int]]]) -> None:
    """A plain RGBA PNG (stdlib only)."""
    h, w = len(pixels), len(pixels[0])
    raw = b"".join(b"\x00" + bytes(v for px in row for v in px) for row in pixels)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    blob = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    blob += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(blob)


def render(grids: list[list[Grid | None]], scale: int, gap: int = 2) -> list[list[tuple[int, int, int, int]]]:
    """Lays chunks out in rows (None = an empty cell), each pixel a scale x scale block, a dark gap between chunks."""
    rows, cols = len(grids), max(len(r) for r in grids)
    cell = SIZE * scale
    w, h = cols * cell + (cols + 1) * gap, rows * cell + (rows + 1) * gap
    out = [[(24, 26, 32, 255)] * w for _ in range(h)]
    for r, row in enumerate(grids):
        for c, g in enumerate(row):
            if g is None:
                continue
            ox, oy = gap + c * (cell + gap), gap + r * (cell + gap)
            for y in range(SIZE):
                for x in range(SIZE):
                    idx = g.px[y][x]
                    rgba = (40, 44, 52, 255) if idx == 0 else (*PALETTE[idx], 255)
                    for yy in range(scale):
                        line = out[oy + y * scale + yy]
                        for xx in range(scale):
                            line[ox + x * scale + xx] = rgba
    return out


def previews(key: str, parts: dict[str, list[Grid]], folder: Path) -> list[Path]:
    folder.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name in PARTS:
        chunks = parts[name]
        for i, g in enumerate(chunks):
            p = folder / f"{key}_{name}_{i}.png"
            png(p, render([[g]], 8))
            written.append(p)
        cols = COLUMNS[name]
        layout = [chunks[r * cols:(r + 1) * cols] for r in range(len(chunks) // cols)]
        p = folder / f"{key}_{name}.png"
        png(p, render(layout, 6))
        written.append(p)

    # The overview: every part's canvas as the editor shows it, then a rough front view (right arm | torso | left arm,
    # the legs below — the chunks are not to scale, it only shows how the colours meet).
    a, l = parts["arms"], parts["legs"]
    sheet = [
        parts["torso"] + [None],
        a[0:4] + [None],
        a[4:8] + [None],
        l[0:4] + [None],
        l[4:8] + [None],
        parts["helmet"],
        [None, a[4], parts["torso"][0], a[0], None],
        [None, l[4], None, l[0], None],
    ]
    p = folder / f"{key}_overview.png"
    png(p, render(sheet, 4, gap=4))
    written.append(p)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only validate data/skins.json")
    parser.add_argument("--preview", type=Path, help="write PNG previews of every chunk into this folder")
    args = parser.parse_args()

    if args.check:
        problems = validate(load())
        for p in problems:
            print("error:", p)
        return 1 if problems else 0

    data = load()
    made = generated()
    made_keys = {s["key"] for s, _ in made}
    kept = [s for s in data.get("skins", []) if s.get("key") not in made_keys]
    skins = [s for s, _ in made] + kept
    problems = validate({"skins": skins})
    if problems:
        for p in problems:
            print("error:", p)
        return 1

    write(skins)
    print(f"wrote {SKINS.relative_to(REPO)} ({len(skins)} skins)")
    if args.preview:
        for skin, parts in made:
            for p in previews(skin["key"], parts, args.preview):
                print("preview", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
