_ALL = {**EXTRA, **GLYPHS}


def glyph(ch: str) -> tuple[int, ...] | None:
    """The 7 rows of a character, or None for one the font does not draw."""
    return _ALL.get(ch)


def line_width(text: str) -> int:
    """A line's width in font pixels: one advance per character, without the trailing spacing."""
    return len(text) * ADVANCE - 1 if text else 0


def ink(text: str) -> list[tuple[int, int]]:
    """Every ink pixel of a line as (column, row): column 0 at the left, row 0 at the TOP, row 6 the baseline."""
    pixels = []
    for i, ch in enumerate(text):
        rows = glyph(ch)
        if rows is None:
            continue
        for row, bits in enumerate(rows):
            for col in range(WIDTH):
                if bits & (1 << (WIDTH - 1 - col)):
                    pixels.append((i * ADVANCE + col, row))
    return pixels
