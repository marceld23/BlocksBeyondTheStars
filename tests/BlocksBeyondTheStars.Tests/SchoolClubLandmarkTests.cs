/// <summary>
/// The school club's landmarks as shipped (data/landmarks/*.json, generated by tools/landmarks/&lt;key&gt;.py): each one loads
/// without a problem, is rolled (or fixed on its planet type) as the spec says, has its name and Codex text in English and
/// German, keeps its cell count under a budget, is seated on a generation-39 world as one overlay under a budget without a
/// block edit, is protected exactly when it stands intact — and a ruin decays differently for two seeds. One row per landmark;
/// the builders of the package add theirs.
/// </summary>
public sealed class SchoolClubLandmarkTests : IDisposable
{
    private static readonly Lazy<GameContent> Shipped = new(() => ContentLoader.LoadFromDirectory(TestPaths.DataDir()));

    private readonly string _root = Path.Combine(Path.GetTempPath(), "bbts_club_landmarks_" + Guid.NewGuid().ToString("N"));
    private readonly List<SqliteWorldRepository> _repos = new();
    private readonly ITestOutputHelper _output;

    public SchoolClubLandmarkTests(ITestOutputHelper output) => _output = output;

    public void Dispose()
    {
        _repos.ForEach(r => r.Dispose());
        Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();
        try
        {
            Directory.Delete(_root, recursive: true);
        }
        catch (IOException)
        {
            // best effort — a still-open SQLite handle on Windows
        }
    }

    private static StructureTemplate Template(string key)
    {
        var t = Shipped.Value.Landmarks.SingleOrDefault(l => l.Key == key);
        Assert.True(t is not null, $"data/landmarks/{key}.json is missing or was dropped at load");
        return t!;
    }

    // ---------------------------------------------------------------- the template

    /// <summary>Loads cleanly, rolled or fixed as the spec says, named, sized within the limit, its cells within a budget.</summary>
    [Theory]
    [InlineData("eifelnyde", "", 900_000)]
    [InlineData("suspension_bridge", "", 120_000)]
    [InlineData("old_mine", "", 400_000)]
    [InlineData("leaning_tower", "", 60_000)]
    [InlineData("porta_nigra", "", 150_000)]
    [InlineData("portasseum", "", 300_000)]
    [InlineData("golden_bird_gate", "", 160_000)]
    [InlineData("soaniri_castle", "sounder_world", 160_000)]
    [InlineData("singer_statue", "sounder_world", 50_000)]
    [InlineData("soundi_statue", "", 30_000)]
    [InlineData("blocks_king", "", 50_000)]
    public void TheTemplate_LoadsCleanly_IsRolledOrFixed_AndKeepsItsCellBudget(string key, string fixedOnType, int maxCells)
    {
        var t = Template(key);
        Assert.True(t.Landmark);
        Assert.Empty(LandmarkRules.Problems(t));
        Assert.Equal($"landmark.{key}.name", t.NameKey);
        Assert.True(Math.Max(t.Width, Math.Max(t.Height, t.Length)) <= LandmarkRules.MaxSize);
        Assert.False(t.PinOnly);
        Assert.Equal(WorldDescription.SchoolClubLandmarksGeneration, t.MinTerrainGeneration); // never rolled on an older world
        if (fixedOnType.Length > 0)
        {
            Assert.Contains(key, Shipped.Value.GetPlanet(fixedOnType)!.FixedLandmarks);
        }

        foreach (string locale in new[] { "en", "de" })
        {
            var table = JsonSerializer.Deserialize<Dictionary<string, string>>(
                File.ReadAllText(Path.Combine(TestPaths.DataDir(), "locales", locale + ".json")))!;
            Assert.False(string.IsNullOrWhiteSpace(table.GetValueOrDefault($"landmark.{key}.name")), $"{locale}: no name for {key}");
            Assert.False(string.IsNullOrWhiteSpace(table.GetValueOrDefault($"landmark.{key}.desc")), $"{locale}: no Codex text for {key}");
        }

        int cells = TemplateBody.CellCount(t);
        _output.WriteLine($"{key}: {t.Width}×{t.Height}×{t.Length}, {cells} cells");
        Assert.True(cells <= maxCells, $"{key}: {cells} cells, the budget is {maxCells}");
    }

    /// <summary>A ruin decays differently for two seeds (and the same for one); an intact landmark is the same for every seed.</summary>
    [Theory]
    [InlineData("eifelnyde")]
    [InlineData("suspension_bridge")]
    [InlineData("old_mine")]
    [InlineData("leaning_tower")]
    [InlineData("porta_nigra")]
    [InlineData("portasseum")]
    [InlineData("golden_bird_gate")]
    [InlineData("soaniri_castle")]
    [InlineData("singer_statue")]
    [InlineData("soundi_statue")]
    [InlineData("blocks_king")]
    public void ARuin_DecaysDifferentlyForTwoSeeds(string key)
    {
        var t = Template(key);
        var a = LandmarkGenerator.Build(t, 1, 0, Shipped.Value, "grass");
        var b = LandmarkGenerator.Build(t, 2, 0, Shipped.Value, "grass");
        var again = LandmarkGenerator.Build(t, 1, 0, Shipped.Value, "grass");
        Assert.Equal(LandmarkRules.IsRuin(t), a.Ruined);
        Assert.Equal(Blocks(a), Blocks(again));
        if (a.Ruined)
        {
            Assert.NotEqual(Blocks(a), Blocks(b));
            _output.WriteLine($"{key}: {Count(a)} / {Count(b)} blocks left of {Count(LandmarkGenerator.Build(t, 1, 0, Shipped.Value, "grass", ruin: false))}");
        }
        else
        {
            Assert.Equal(Blocks(a), Blocks(b));
        }
    }

    private static ushort[] Blocks(LandmarkLayout l)
    {
        var s = l.Structure;
        var all = new ushort[s.Width * s.Height * s.Length];
        int i = 0;
        for (int x = 0; x < s.Width; x++)
        {
            for (int y = 0; y < s.Height; y++)
            {
                for (int z = 0; z < s.Length; z++)
                {
                    all[i++] = s.Get(x, y, z);
                }
            }
        }

        return all;
    }

    private static int Count(LandmarkLayout l) => Blocks(l).Count(b => b != 0);

    // ---------------------------------------------------------------- on a world

    private SvGameServer Start(GameContent content, string name, string planet, long seed)
    {
        var repo = new SqliteWorldRepository(new SaveGamePaths(_root, name));
        _repos.Add(repo);
        var config = new ServerConfig
        {
            WorldName = name,
            Seed = seed,
            StartPlanet = planet,
            AutoSaveIntervalMinutes = 9999,
            PlaceStarterShip = false,
            PlaceSettlements = false,
            LandmarkChance = 1.0,
        };
        config.World.TerrainGeneration = WorldDescription.SchoolClubLandmarksGeneration;
        var server = new SvGameServer(config, content, new LoopbackServerTransport(new LoopbackLink()), repo);
        server.Start();
        return server;
    }

    /// <summary>
    /// The landmark alone in the pool of a generation-39 world on a planet it may stand on: it is seated (a span across a
    /// gap from bank to bank), stored as ONE overlay under the byte budget and without a block edit on it, and a player's
    /// mining of one of its blocks is refused exactly when it stands intact (protected) — a ruin is open.
    /// </summary>
    [Theory]
    [Trait("Category", "Slow")] // a world boot and a stamp of up to 800 000 cells per row
    [InlineData("eifelnyde", "meadowlands", 20261112L, 160 * 1024)]
    [InlineData("suspension_bridge", "meadowlands", 7L, 48 * 1024)] // a span across a lake (it seats in ~2 of 3 boots)
    [InlineData("old_mine", "meadowlands", 7L, 96 * 1024)] // an underground part: a dry, even seat (most bodies have one)
    [InlineData("leaning_tower", "meadowlands", 20261112L, 48 * 1024)]
    [InlineData("porta_nigra", "meadowlands", 20261112L, 112 * 1024)]
    [InlineData("portasseum", "meadowlands", 7L, 192 * 1024)] // the hypogeum: a dry, even seat 192 x 160 (17 of 18 scouted bodies)
    [InlineData("golden_bird_gate", "meadowlands", 20261112L, 96 * 1024)]
    [InlineData("soundi_statue", "meadowlands", 20261112L, 48 * 1024)] // the Soaniri pair and Blocks King: SchoolClubSoaniriLandmarkTests
    public void OnAGeneration39World_ItIsSeated_AsOneOverlayUnderTheBudget_ProtectedOnlyWhenIntact(string key, string planet,
        long seed, int maxOverlayBytes)
    {
        var content = ContentLoader.LoadFromDirectory(TestPaths.DataDir());
        var t = content.Landmarks.Single(l => l.Key == key);
        content.SetLandmarks(new[] { t });
        var server = Start(content, "club_" + key, planet, seed);
        var lm = Assert.Single(server.LandmarksForTest);
        Assert.Equal(key, lm.Key);
        if (LandmarkRules.IsSpanSeat(t))
        {
            Assert.True(server.SpanSeatHoldsForTest(lm), $"{key} does not span a gap from bank to bank");
        }

        var repo = _repos[^1];
        string location = server.World.LocationId;
        var row = Assert.Single(repo.ListStructureOverlays(location), r => r.Key == "landmark:0");
        Assert.True(StructureOverlay.TryDecode(row.Data, out var overlay));
        var cells = new HashSet<Vector3i>(overlay.Cells().Select(c => c.Cell));
        Assert.Empty(overlay.Chunks.SelectMany(c => repo.LoadChunkEdits(location, c.Coord)).Where(e => cells.Contains(e.WorldPosition)));
        _output.WriteLine($"{key} on {planet}: origin {lm.Origin}, turns {lm.Layout.Turns}, {(lm.Layout.Ruined ? "ruin" : "intact")}, " +
                          $"{overlay.CellCount} overlay cells in {overlay.Chunks.Count} chunks, {row.Data.Length} bytes");
        Assert.True(row.Data.Length <= maxOverlayBytes, $"{key}: an overlay of {row.Data.Length} bytes, the budget is {maxOverlayBytes}");

        var s = lm.Structure;
        var block = Enumerable.Range(0, s.Width * s.Length)
            .Select(i => new Vector3i(i / s.Length, lm.Layout.GroundRow + 2, i % s.Length))
            .First(p => s.Get(p.X, p.Y, p.Z) != 0);
        var world = WorldConstants.CanonicalBlock(lm.Cell(block), server.World.Circumference);
        Assert.Equal(!lm.Layout.Ruined, server.IsProtectedStructureCellForTest(world));
        Assert.False(server.IsProtectedStructureCellForTest(world, isAdmin: true));
        server.Stop();
    }

    // ---------------------------------------------------------------- previews (on demand)

    /// <summary>
    /// Writes the ruins of the landmarks named in <c>BBTS_RUIN_PREVIEW_KEYS</c> (comma list) for seeds 1 and 2 (or the comma
    /// list in <c>BBTS_RUIN_PREVIEW_SEEDS</c>) as template files into the folder <c>BBTS_RUIN_PREVIEW</c>, for
    /// <c>tools/landmarks/preview.py</c>, each with the share of the intact landmark's blocks that fell. Does nothing without
    /// them — a builder's tool, not a check.
    /// </summary>
    [Fact]
    public void RuinPreviews_AreWrittenWhenAsked()
    {
        string? folder = Environment.GetEnvironmentVariable("BBTS_RUIN_PREVIEW");
        string? keys = Environment.GetEnvironmentVariable("BBTS_RUIN_PREVIEW_KEYS");
        if (string.IsNullOrWhiteSpace(folder) || string.IsNullOrWhiteSpace(keys))
        {
            return;
        }

        var seeds = (Environment.GetEnvironmentVariable("BBTS_RUIN_PREVIEW_SEEDS") ?? "1,2")
            .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(s => long.Parse(s, System.Globalization.CultureInfo.InvariantCulture)).ToList();
        Directory.CreateDirectory(folder);
        foreach (string key in keys.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var t = Template(key);
            int intact = Count(LandmarkGenerator.Build(t, 1, 0, Shipped.Value, "grass", ruin: false));
            foreach (long seed in seeds)
            {
                var layout = LandmarkGenerator.Build(t, seed, 0, Shipped.Value, "grass", ruin: true);
                string path = Path.Combine(folder, $"{key}_ruin{seed}.json");
                File.WriteAllText(path, JsonSerializer.Serialize(AsTemplate(t, layout, seed), PreviewJson));
                int left = Count(layout);
                _output.WriteLine($"{path}: {left} of {intact} blocks ({100.0 * (intact - left) / intact:0.0} % fell), " +
                                  $"{layout.Structure.Markers.Count} markers");
            }
        }
    }

    private static readonly JsonSerializerOptions PreviewJson = new() { PropertyNamingPolicy = JsonNamingPolicy.CamelCase };

    /// <summary>A built layout as a compact template (blocks, cavities, markers), for the preview.</summary>
    private static StructureTemplate AsTemplate(StructureTemplate source, LandmarkLayout layout, long seed)
    {
        var s = layout.Structure;
        var t = new StructureTemplate
        {
            Key = $"{source.Key}_ruin{seed}",
            Name = $"{source.Name} (ruin, seed {seed})",
            Landmark = true,
            Width = s.Width,
            Height = s.Height,
            Length = s.Length,
            GroundRow = layout.GroundRow,
            RuinZones = source.RuinZones,
        };
        for (int x = 0; x < s.Width; x++)
        {
            for (int y = 0; y < s.Height; y++)
            {
                for (int z = 0; z < s.Length; z++)
                {
                    ushort id = s.Get(x, y, z);
                    if (id != 0)
                    {
                        var (tint, glow) = s.GetModifier(x, y, z);
                        t.Cells.Add(new TemplateCell
                        {
                            X = x,
                            Y = y,
                            Z = z,
                            Id = Shipped.Value.BlockById(new Shared.Primitives.BlockId(id))!.Key,
                            Tint = tint,
                            Glow = glow,
                            Shape = s.GetShape(x, y, z),
                        });
                    }
                    else if (layout.IsCavity(x, y, z))
                    {
                        t.Cells.Add(new TemplateCell { X = x, Y = y, Z = z, Kind = LandmarkRules.CavityKind });
                    }
                }
            }
        }

        foreach (var m in s.Markers)
        {
            t.Cells.Add(new TemplateCell { X = m.LocalPos.X, Y = m.LocalPos.Y, Z = m.LocalPos.Z, Kind = "marker", Id = m.Type, Config = m.Data });
        }

        TemplateBody.Compact(t);
        return t;
    }
}
